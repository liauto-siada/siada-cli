export interface BrowserToolParams {
  action: "tabs" | "read" | "execute" | "replay" | "screenshot" | "paragraphs" | "annotate" | "pdf_render";
  tabId?: number;   // Required for read/execute/replay/screenshot/paragraphs/annotate
  script?: string;  // Required for execute
  step?: ReplayStep; // Required for replay
  offset?: number;  // Optional for read: char offset into the serialized DOM (default 0)
  limit?: number;   // Optional for read: max chars of DOM to return (default 50000)
  maxWidth?: number; // Optional for screenshot: downscale to this width in px (default 1280)
  quality?: number;  // Optional for screenshot: JPEG quality 0-100 (default 70)
  items?: AnnotateItem[]; // For annotate: translation/explanation blocks to insert
  clear?: boolean;  // For annotate: remove all previously injected annotations
  pdfUrl?: string;  // Required for pdf_render: http/https/file URL of the PDF document
  page?: number;    // Optional for pdf_render: initial page to scroll to
}

// One translation/explanation block to render into the page.
// With `index`: inserted directly below the paragraph tagged by browser_paragraphs.
// Without `index`: shown in the page-level floating answer card.
// On PDF viewer tabs (opened via browser_pdf_render): `index` is the 1-based
// PAGE number, and annotations use pdf.js's native annotation editors, so
// they can be saved into the PDF (see the annotate tool description).
export interface AnnotateItem {
  index?: number;
  text: string;
  /** Visual style hint: translation (default) or explanation */
  kind?: "translation" | "explanation" | "highlight" | "freetext";
  /** PDF viewer only: note position/size as page fractions, top-left origin */
  x?: number;
  y?: number;
  width?: number;
  height?: number;
  /** PDF viewer only: text color [r,g,b], 0-255 */
  color?: number[];
  /** PDF viewer only: FreeText font size in pt */
  fontSize?: number;
  /** PDF viewer only: popup comment attached to the annotation */
  comment?: string;
}

// A single deterministic replay step (from a saved task pipeline).
// Element location tries selector, then xpath, then visible text.
export interface ReplayStep {
  kind: "click" | "input" | "select" | "keydown" | "scroll" | "navigate";
  target?: TrajectoryTarget; // Not needed for scroll/navigate
  value?: string;            // input/select value; checkbox: "true"/"false"
  key?: string;              // keydown
  url?: string;              // navigate
  scrollX?: number;          // scroll
  scrollY?: number;          // scroll
}

