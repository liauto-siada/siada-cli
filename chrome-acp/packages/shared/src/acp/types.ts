// ============================================================================
// Trajectory Recording Types
// ============================================================================
// Semantic user-operation events recorded by the extension content script,
// forwarded by the background service worker to the proxy-server, and written
// to ~/.chrome-acp/trajectories/YYYY-MM-DD.jsonl for agents to distill into
// reusable task pipelines.
// ============================================================================

/** Re-locatable description of a DOM element (no replay ids needed) */
export interface TrajectoryTarget {
  tag: string;
  /** CSS selector path (best-effort, may not be unique) */
  selector: string;
  /** Absolute XPath as fallback */
  xpath: string;
  /** Visible text snippet (<= 50 chars) */
  text?: string;
  /** ARIA role (explicit attribute only) */
  role?: string;
  /** aria-label if present */
  ariaLabel?: string;
}

export type TrajectoryActionKind = "click" | "input" | "select" | "keydown" | "scroll";

export interface TrajectoryActionEvent {
  ts: number;
  type: "action";
  url: string;
  title: string;
  /** Filled by the background service worker */
  tabId?: number;
  action: {
    kind: TrajectoryActionKind;
    target?: TrajectoryTarget;
    /** Masked as "***" for password / data-acp-mask inputs */
    value?: string;
    /** For keydown: Enter | Tab */
    key?: string;
    /** For scroll */
    scrollX?: number;
    scrollY?: number;
  };
  /** Semantic summary of DOM changes triggered by this action */
  response?: string;
}

export interface TrajectoryNavigationEvent {
  ts: number;
  type: "navigation";
  url: string;
  title: string;
  /** Filled by the background service worker */
  tabId?: number;
}

export type TrajectoryEvent = TrajectoryActionEvent | TrajectoryNavigationEvent;
